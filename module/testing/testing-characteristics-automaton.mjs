/**
 * The automaton characteristic suite.
 *
 * Every test reads an uploaded Hero Designer export. `before` uploads one export per describe, and
 * `after` deletes that actor, so no test reads an actor another test changed. No test reads a bare
 * actor: the export is the subject.
 *
 * The Automaton power decides STUN, and the option decides the answer. "Cannot Be Stunned" keeps the
 * STUN characteristic and changes how STUN damage applies. "Takes No STUN", in either form, removes STUN
 * from the actor. The rows below state that for each option, so an option that stops removing STUN
 * fails here.
 *
 * The `FIXTURES` table holds every expectation. Read a row to know what the suite checks. To cover a
 * new export, add a row.
 *
 * Fixture strings belong to this suite. Do not lift them into a shared module, and do not state a value
 * for a name the export does not hold. Every actor type stores a node for every name, so such a test
 * passes whatever the actor did.
 */

